#!/usr/bin/env python3
"""Exercise preflight against isolated repositories and deterministic tool stubs."""

import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).with_name("agent-preflight.py").resolve()
SOURCE = SCRIPT.parent.parent
GIT = shutil.which("git")


class PreflightTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="sidequest-preflight-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / "repo"
        self.root.mkdir()
        self.bin = Path(self.temp.name) / "bin"
        self.bin.mkdir()
        self.env = dict(os.environ, GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", PATH=str(self.bin))
        # Keep Git real; replace external services and the Xcode dependency.
        for name, source in (("git", GIT), ("python3", sys.executable)):
            (self.bin / name).symlink_to(source)
        self.stub("gh", 'if [ "$1" = "--version" ]; then echo gh-test; else echo devofthings/sidequest; fi')
        self.stub("xcrun", "echo swift-format-test")
        self.stub("xcodebuild", "echo Xcode-test")
        self.git("init", "-q")
        self.git("config", "user.name", "Fixture")
        self.git("config", "user.email", "fixture@example.invalid")
        self.git("checkout", "-qb", "codex/62-fixture")
        self.git("remote", "add", "origin", "https://github.com/devofthings/sidequest.git")
        (self.root / ".githooks").mkdir()
        shutil.copy2(SOURCE / ".githooks/pre-commit", self.root / ".githooks/pre-commit")
        (self.root / ".agents/skills/my-review").mkdir(parents=True)
        shutil.copy2(SOURCE / ".agents/skills/my-review/SKILL.md", self.root / ".agents/skills/my-review/SKILL.md")
        shutil.copy2(SOURCE / ".swift-format", self.root / ".swift-format")
        self.git("add", ".")
        self.git("commit", "-qm", "fixture")
        self.git("config", "core.hooksPath", ".githooks")

    def stub(self, name, body):
        path = self.bin / name
        path.write_text("#!/bin/sh\n" + body + "\n")
        path.chmod(0o755)

    def git(self, *args):
        return subprocess.run([GIT, *args], cwd=self.root, env=self.env, check=True, capture_output=True, text=True).stdout

    def run_preflight(self):
        return subprocess.run([sys.executable, str(SCRIPT)], cwd=self.root, env=self.env, capture_output=True, text=True)

    def reject(self, fragment):
        result = self.run_preflight()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn(fragment, result.stdout)

    def test_valid_checkout_is_read_only(self):
        before = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        result = self.run_preflight()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        after = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        self.assertEqual(before, after)
        self.assertIn("App build, gameplay tests, and releases unavailable", result.stdout)

    def test_wrong_remote(self):
        self.git("remote", "set-url", "origin", "https://github.com/other/project.git")
        self.reject("FAIL repository origin")

    def test_ssh_remote(self):
        self.git("remote", "set-url", "origin", "git@github.com:devofthings/sidequest.git")
        self.assertEqual(self.run_preflight().returncode, 0)

    def test_main_branch(self):
        self.git("checkout", "-qb", "main")
        self.reject("FAIL feature branch")

    def test_branch_without_issue(self):
        self.git("checkout", "-qb", "codex/no-issue")
        self.reject("FAIL feature branch")

    def test_detached_head(self):
        self.git("checkout", "--detach", "-q")
        self.reject("FAIL feature branch")

    def test_dirty_checkout(self):
        (self.root / "untracked.txt").write_text("preserve me")
        self.reject("FAIL clean checkout")
        self.assertEqual((self.root / "untracked.txt").read_text(), "preserve me")

    def test_missing_skill(self):
        (self.root / ".agents/skills/my-review/SKILL.md").unlink()
        self.reject("FAIL local review skill")

    def test_missing_hook_configuration(self):
        self.git("config", "--unset", "core.hooksPath")
        self.reject("FAIL Sidequest hooks")
        self.assertEqual(self.git("config", "--local", "--list").find("hookspath"), -1)

    def test_unknown_hook(self):
        self.git("config", "core.hooksPath", "other-hooks")
        self.reject("FAIL Sidequest hooks")

    def test_forwarded_hook(self):
        # Reuse the production constants without import-generated bytecode.
        namespace = {"__name__": "preflight_test"}
        exec(compile(SCRIPT.read_text(), str(SCRIPT), "exec"), namespace)
        forwarding = Path(self.temp.name) / "forwarding"
        forwarding.mkdir()
        (forwarding / "pre-commit").write_text(namespace["FORWARDER"])
        (forwarding / "pre-commit").chmod(0o755)
        dispatcher = self.root / ".git/hooks/pre-commit"
        dispatcher.write_text(namespace["DISPATCHER"])
        dispatcher.chmod(0o755)
        self.git("config", "core.hooksPath", str(forwarding))
        self.assertEqual(self.run_preflight().returncode, 0)
        dispatcher.write_text("#!/bin/sh\nexit 0\n")
        self.reject("FAIL Sidequest hooks")

    def test_missing_tool(self):
        (self.bin / "gh").unlink()
        self.reject("FAIL tool gh")

    def test_no_github_access(self):
        self.stub("gh", 'if [ "$1" = "--version" ]; then echo gh-test; else echo denied >&2; exit 1; fi')
        self.reject("FAIL GitHub access")

    def test_missing_xcode(self):
        self.stub("xcodebuild", "echo unavailable >&2; exit 1")
        self.reject("FAIL Xcode")

    def test_missing_formatter(self):
        self.stub("xcrun", "echo unavailable >&2; exit 1")
        self.reject("FAIL swift-format")

    def test_missing_format_configuration(self):
        (self.root / ".swift-format").unlink()
        self.reject("FAIL format configuration")


if __name__ == "__main__":
    unittest.main()
